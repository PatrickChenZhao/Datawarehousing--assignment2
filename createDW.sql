PROMPT ===== CREATING PF_TRANSACTION_FACT =====

CREATE TABLE PF_TRANSACTION_FACT (
    TRANSACTION_KEY       NUMBER(12)    NOT NULL,
    SOURCE_TRANSACTION_ID VARCHAR2(30)  NOT NULL,
    TRANSACTION_LINE_NO   NUMBER(4)     NOT NULL,
    DATE_KEY              NUMBER(8)     NOT NULL,
    STORE_KEY             NUMBER(10)    NOT NULL,
    CUSTOMER_KEY          NUMBER(10)    NOT NULL,
    PRODUCT_KEY           NUMBER(10)    NOT NULL,
    QUANTITY              NUMBER(10)    NOT NULL,
    UNIT_SELLING_PRICE    NUMBER(12,2)  NOT NULL,
    UNIT_COST             NUMBER(12,2)  NOT NULL,
    SALES_AMOUNT          NUMBER(14,2)  NOT NULL,
    COST_AMOUNT           NUMBER(14,2)  NOT NULL,
    CONSTRAINT PF_TXN_PK PRIMARY KEY (TRANSACTION_KEY),
    CONSTRAINT PF_TXN_SRC_LINE_UK
        UNIQUE (STORE_KEY, SOURCE_TRANSACTION_ID, TRANSACTION_LINE_NO),
    CONSTRAINT PF_TXN_DATE_FK FOREIGN KEY (DATE_KEY)
        REFERENCES PF_DATE_DIM (DATE_KEY),
    CONSTRAINT PF_TXN_STORE_FK FOREIGN KEY (STORE_KEY)
        REFERENCES PF_STORE_DIM (STORE_KEY),
    CONSTRAINT PF_TXN_CUST_FK FOREIGN KEY (CUSTOMER_KEY)
        REFERENCES PF_CUSTOMER_DIM (CUSTOMER_KEY),
    CONSTRAINT PF_TXN_PRODUCT_FK FOREIGN KEY (PRODUCT_KEY)
        REFERENCES PF_PRODUCT_DIM (PRODUCT_KEY),
    CONSTRAINT PF_TXN_LINE_CK CHECK (TRANSACTION_LINE_NO > 0),
    CONSTRAINT PF_TXN_QTY_CK CHECK (QUANTITY > 0),
    CONSTRAINT PF_TXN_UPRICE_CK CHECK (UNIT_SELLING_PRICE >= 0),
    CONSTRAINT PF_TXN_UCOST_CK CHECK (UNIT_COST >= 0),
    CONSTRAINT PF_TXN_SALES_CK CHECK (SALES_AMOUNT >= 0),
    CONSTRAINT PF_TXN_COST_CK CHECK (COST_AMOUNT >= 0)
);

COMMENT ON TABLE PF_TRANSACTION_FACT IS
    'One row per accessory sale line or repair-service line in a source transaction';
COMMENT ON COLUMN PF_TRANSACTION_FACT.SOURCE_TRANSACTION_ID IS
    'Store-supplied transaction identifier retained as a degenerate dimension';
COMMENT ON COLUMN PF_TRANSACTION_FACT.QUANTITY IS
    'Units sold or repair-service count; fully additive';
COMMENT ON COLUMN PF_TRANSACTION_FACT.SALES_AMOUNT IS
    'Transaction-line revenue; fully additive';
COMMENT ON COLUMN PF_TRANSACTION_FACT.COST_AMOUNT IS
    'Transaction-line cost; fully additive';

