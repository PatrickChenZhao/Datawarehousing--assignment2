CREATE TABLE PF_DATE_DIM (
    DATE_KEY         NUMBER(8)    NOT NULL,
    FULL_DATE        DATE         NOT NULL,
    DAY_OF_MONTH     NUMBER(2)    NOT NULL,
    DAY_NAME         VARCHAR2(9)  NOT NULL,
    WEEK_OF_YEAR     NUMBER(2)    NOT NULL,
    MONTH_NUMBER     NUMBER(2)    NOT NULL,
    MONTH_NAME       VARCHAR2(9)  NOT NULL,
    QUARTER_NUMBER   NUMBER(1)    NOT NULL,
    CALENDAR_YEAR    NUMBER(4)    NOT NULL,
    WEEKEND_FLAG     CHAR(1)      NOT NULL,
    CONSTRAINT PF_DATE_PK PRIMARY KEY (DATE_KEY),
    CONSTRAINT PF_DATE_FULL_UK UNIQUE (FULL_DATE),
    CONSTRAINT PF_DATE_DAY_CK CHECK (DAY_OF_MONTH BETWEEN 1 AND 31),
    CONSTRAINT PF_DATE_WEEK_CK CHECK (WEEK_OF_YEAR BETWEEN 1 AND 53),
    CONSTRAINT PF_DATE_MONTH_CK CHECK (MONTH_NUMBER BETWEEN 1 AND 12),
    CONSTRAINT PF_DATE_QTR_CK CHECK (QUARTER_NUMBER BETWEEN 1 AND 4),
    CONSTRAINT PF_DATE_WEND_CK CHECK (WEEKEND_FLAG IN ('Y', 'N'))
);

COMMENT ON TABLE PF_DATE_DIM IS
    'Calendar dimension for consistent day, week, month, quarter and year analysis';
COMMENT ON COLUMN PF_DATE_DIM.DATE_KEY IS
    'Warehouse date key using the YYYYMMDD convention';

